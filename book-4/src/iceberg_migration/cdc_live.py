import uuid
from pathlib import Path

from .common import Refused,digest,write_json,read_json
from .postgres import connect


def prepare(work):
    from psycopg import sql
    root=Path(__file__).resolve().parents[3]
    namespace='migr_'+uuid.uuid4().hex[:12]
    db=connect()
    try:
        with db.transaction():
            db.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(namespace)))
            db.execute(sql.SQL('CREATE TABLE {}.orders (order_id INT PRIMARY KEY,customer_id INT NOT NULL,order_date DATE NOT NULL,status TEXT NOT NULL)').format(sql.Identifier(namespace)))
            db.execute(sql.SQL("INSERT INTO {}.orders SELECT 51000+i,100+i,DATE '2026-09-01','paid' FROM generate_series(1,8) AS i").format(sql.Identifier(namespace)))
        template=(root/'book-2/flink/sql/cdc-from-debezium.sql').read_text()
        ddl=template.replace('ice.stage4',f'ice.{namespace}').replace('bookshop.public.orders',f'{namespace}.{namespace}.orders').replace('flink-stage4c',namespace)
        # A repeated submission must fail visibly instead of dropping a live sink.
        ddl='\n'.join(line for line in ddl.splitlines() if not line.startswith('DROP TABLE IF EXISTS'))+'\n'
        (work/'flink.sql').write_text(ddl)
        connector={'name':namespace,'config':{'connector.class':'io.debezium.connector.postgresql.PostgresConnector',
          'database.hostname':'host.docker.internal','database.port':'5544','database.user':'migration',
          'database.password':'SET_PRIVATELY_BEFORE_SUBMISSION','database.dbname':'sqlverify','topic.prefix':namespace,
          'schema.include.list':namespace,'table.include.list':namespace+'.orders','plugin.name':'pgoutput',
          'slot.name':namespace,'publication.name':namespace,'publication.autocreate.mode':'filtered','snapshot.mode':'initial'}}
        write_json(work/'connector-template.json',connector)
        manifest={'namespace':namespace,'source_database':'sqlverify','source_table':namespace+'.orders',
                  'landing_table':'ice.'+namespace+'.orders_cdc','migration_table':'ice.'+namespace+'.orders_backfill',
                  'book2_sql_sha256':digest(template),'generated_flink_sql_sha256':digest(ddl),'submitted':False,
                  'connector_name':namespace,'source_rows':8,'scope':'owned four-column CDC fixture, separate from nine-column report pilot'}
        write_json(work/'cdc-manifest.json',manifest);return manifest
    finally:db.close()


def exercise(work,manifest_path):
    from psycopg import sql
    manifest=read_json(manifest_path);ns=manifest['namespace']
    if not re.fullmatch(r'migr_[a-f0-9]{12}',ns):raise Refused('Use the namespace generated by cdc-prepare')
    if manifest['source_table']!=ns+'.orders' or manifest['landing_table']!='ice.'+ns+'.orders_cdc':raise Refused('CDC manifest identifiers disagree')
    root=Path(__file__).resolve().parents[3]
    sys.path.insert(0,str(root/'book-2'))
    spec=importlib.util.spec_from_file_location('book2_convergence',root/'book-2/cdc/convergence_test.py')
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
    reader=connect();writer=connect();spark=module.spark('migration-boundary',cores=2)
    landing=manifest['landing_table'];target='ice.'+ns+'.orders_backfill'
    def pg_rows(db):
        return [(int(a),int(b),(day-__import__('datetime').date(1970,1,1)).days,status) for a,b,day,status in db.execute(sql.SQL('SELECT order_id,customer_id,order_date,status FROM {}.orders ORDER BY order_id').format(sql.Identifier(ns))).fetchall()]
    def state_from_rows(values):
        from collections import Counter
        return len(values),sum(r[0] for r in values),sum(r[1] for r in values),dict(Counter(r[3] for r in values))
    try:
        # Reuse the existing convergence algorithm with this owned source adapter.
        baseline=pg_rows(writer);writer.commit()
        if [r[0] for r in baseline]!=list(range(51001,51009)) or any(r[3]!='paid' for r in baseline):raise Refused('CDC exercise requires its untouched prepared source; prepare a fresh run')
        module.pg_state=lambda:state_from_rows(baseline)
        module.converge(lambda q:spark.sql(q).collect(),landing,timeout=300)
        reader.execute('BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY')
        before=pg_rows(reader)
        snapshot=reader.execute('SELECT pg_current_snapshot()::text').fetchone()[0]
        with writer.transaction():
            writer.execute(sql.SQL("UPDATE {}.orders SET status='refunded' WHERE order_id=51001").format(sql.Identifier(ns)))
            writer.execute(sql.SQL('DELETE FROM {}.orders WHERE order_id=51002').format(sql.Identifier(ns)))
            writer.execute(sql.SQL("INSERT INTO {}.orders VALUES (51999,999,DATE '2026-09-02','paid')").format(sql.Identifier(ns)))
        assert pg_rows(reader)==before,'Backfill snapshot changed while open'
        reader.commit()
        after=pg_rows(writer);writer.commit()
        module.pg_state=lambda:state_from_rows(after)
        module.converge(lambda q:spark.sql(q).collect(),landing,timeout=300)
        source_schema='order_id int, customer_id int, order_date int, status string'
        spark.createDataFrame(before,schema=source_schema).writeTo(target).using('iceberg').tableProperty('format-version','2').create()
        def image(table):return [tuple(r) for r in spark.sql(f'SELECT order_id,customer_id,order_date,status FROM {table} ORDER BY order_id').collect()]
        observed_landing=image(landing)
        assert observed_landing==after,'Aggregate convergence hid an exact row mismatch'
        merge=f'MERGE INTO {target} t USING {landing} s ON t.order_id=s.order_id WHEN MATCHED THEN UPDATE SET * WHEN NOT MATCHED THEN INSERT *'
        spark.sql(merge).collect()
        assert image(target)!=after,'The deliberately missing delete clause did not expose its planted defect'
        spark.sql(merge+' WHEN NOT MATCHED BY SOURCE THEN DELETE').collect()
        first=image(target);assert first==after
        spark.sql(merge+' WHEN NOT MATCHED BY SOURCE THEN DELETE').collect();assert image(target)==first
        result={'status':'passed','namespace':ns,'source_snapshot':snapshot,'backfill_rows':len(before),'final_rows':len(after),
                'source_changed_while_backfill_snapshot_open':True,'exact_landing_match':True,'omitted_delete_detected':True,'merge_replay_idempotent':True,
                'scope':'actual owned source overlap and current-image handoff through Book 2 CDC; no claim that a SQL snapshot is a WAL boundary or that connector restart was injected'}
        write_json(work/'cdc-live.json',result);write_json(work/'backfill-rows.json',before);write_json(work/'current-rows.json',after)
        return result
    finally:reader.close();writer.close();spark.stop()
